package sqlgen_test

import (
	"testing"

	"github.com/suhaasya/wisp-go/internal/driver/postgres"
	"github.com/suhaasya/wisp-go/internal/sqlgen"
)

func TestBuildAndDisplaySQLMatchManualSubstitution(t *testing.T) {
	d := postgres.Dialect()
	plan := sqlgen.CommitPlan{
		Updates: []sqlgen.RowUpdate{{
			KeyColumns: []string{"id"},
			KeyValues:  []any{int64(7)},
			Cells: map[string]sqlgen.CellChange{
				"note": {Value: strPtr("done"), Original: strPtr("todo")},
			},
		}},
	}
	stmts, err := sqlgen.BuildCommitStatements(d, sqlgen.CommitSpec{
		Schema: "app", Table: "tasks", Optimistic: true,
	}, plan)
	if err != nil {
		t.Fatal(err)
	}
	if len(stmts) != 1 {
		t.Fatal(stmts)
	}
	display := sqlgen.DisplaySQL(d, stmts[0].SQL, stmts[0].Args)
	// Independent expected string (not generated by DisplaySQL).
	want := `UPDATE "app"."tasks" SET "note" = 'done' WHERE "id" = 7 AND "note" = 'todo'`
	if display != want {
		t.Fatalf("display:\n got %q\nwant %q", display, want)
	}
}
